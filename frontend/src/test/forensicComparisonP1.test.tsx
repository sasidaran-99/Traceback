      expect(intermediateTitles[0]).toHaveTextContent('Connection timeout logged');
      expect(intermediateTitles[1]).toHaveTextContent('Database connection pool saturated');

      // Switch back to Newest First: stable descending tie-breaker keeps evt-3 before evt-2
      fireEvent.click(screen.getByRole('button', { name: 'Newest First' }));
      const reversedTitles = screen.getAllByText(/Connection timeout logged|Database connection pool saturated/i);
